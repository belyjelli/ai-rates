/**
 * Copies TradingView's Lightweight Charts (the standalone production build, from node_modules) into
 * src/web/lwc.generated.ts, which the Worker serves at /assets/lightweight-charts-<version>.js
 * (web/kchart.ts). Run after changing the pinned version in package.json; a test fails until you do.
 *
 *   bun apps/worker/scripts/lwc.ts
 *
 * Served from this origin rather than a CDN because the pages' policy allows scripts from 'self' and
 * by hash only (app/security-headers.ts), and a third origin for one library is a third origin that
 * can serve the page code. The file keeps its own licence banner (Apache 2.0), which the NOTICE asks.
 * biome.json leaves the generated file alone: it is the library's text, byte for byte.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../../..");
const pkg = JSON.parse(
  readFileSync(join(root, "node_modules/lightweight-charts/package.json"), "utf8"),
) as { version: string };
const source = readFileSync(
  join(root, "node_modules/lightweight-charts/dist/lightweight-charts.standalone.production.js"),
  "utf8",
);
const out = `// Generated by apps/worker/scripts/lwc.ts from lightweight-charts ${pkg.version}. Do not edit: run the script.
/** The pinned Lightweight Charts version: part of the file's address, so a new one is a new file. */
export const LWC_VERSION = ${JSON.stringify(pkg.version)};
/** lightweight-charts.standalone.production.js: defines window.LightweightCharts. */
export const LWC_SOURCE = ${JSON.stringify(source)};
`;
writeFileSync(join(import.meta.dir, "../src/web/lwc.generated.ts"), out);
console.log(`lwc.generated.ts: ${pkg.version}, ${source.length} chars`);
